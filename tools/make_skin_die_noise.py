"""Die Noise skin: turns Resources/die_noise_base.png (generated artwork, no text) into the plugin's skin.

    python tools/make_skin_die_noise.py

- Upscales the artwork to 1024 x 1536, removes the little toggle (the plugin draws its own),
  prints the lettering and the Die Noise logo, and writes Resources/skin.png (+ skin_source.png).
- Writes Source/SkinLayout.h with every control position (artwork pixels, 1024 x 1536).
Requires: numpy, pillow, opencv-python.
"""
import pathlib
import cv2
import numpy as np
from PIL import Image, ImageDraw, ImageFilter, ImageFont

ROOT = pathlib.Path(__file__).resolve().parent.parent
W, H = 1024, 1536
FONT = "/usr/share/fonts/opentype/inter/Inter-SemiBold.otf"
SS = 3

# ---- layout (artwork pixels) -------------------------------------------------------------------
KNOBS = {  # name: (cx, cy, top-face radius, caption, caption y)
    "input": (209, 100, 45, "INPUT", 188), "gate": (368, 100, 45, "GATE", 188),
    "blend": (655, 100, 45, "BLEND", 188), "output": (815, 100, 45, "OUTPUT", 188),
    "chill": (508, 503, 82, "DETUNE", 606), "order": (262, 574, 82, "RUIN", 678),
    "sloth": (759, 574, 82, "RING", 678), "rise": (511, 760, 43, "RISE", 832),
}
PREV, NEXT = (311, 262, 36), (712, 262, 36)
LED = (511, 1032, 19)
SWITCH = {"up": (198, 1324, 62), "wayUp": (824, 1324, 62)}
PRESET_WINDOW = (368, 217, 657, 306)
TOGGLE = (476, 329, 546, 357)
TOGGLE_MIRROR_X = 511.0
METER_LAMPS = [57 + i * 24.2 for i in range(11)]
METER_LEFT, METER_RIGHT = (77.0, 97.0), (926.0, 946.0)


def font(size):
    return ImageFont.truetype(FONT, int(size * SS))


def caption(img, x, y, text, size=27):
    d = ImageDraw.Draw(img)
    f = font(size)
    track = size * 0.08 * SS
    widths = [d.textlength(c, font=f) for c in text]
    px = x * SS - (sum(widths) + track * (len(text) - 1)) / 2
    for c, w in zip(text, widths):
        d.text((px + 1.6 * SS, y * SS + 1.6 * SS), c, font=f, fill=(0, 0, 0, 235), anchor="lm")
        d.text((px, y * SS), c, font=f, fill=(224, 224, 224, 255), anchor="lm")
        px += w + track


def main():
    base = Image.open(ROOT / "Resources/die_noise_base.png").convert("RGB")
    img = base.resize((W, H), Image.LANCZOS).filter(ImageFilter.UnsharpMask(radius=1.6, percent=70, threshold=2))

    # remove the painted toggle (the plugin draws its own lever): clone plain panel texture over it
    arr = cv2.cvtColor(np.asarray(img), cv2.COLOR_RGB2BGR)
    src = cv2.getRectSubPix(arr, (120, 120), (607, 342)).astype(np.float32)
    soft = np.zeros((120, 120), np.float32)
    cv2.circle(soft, (60, 60), 38, 1.0, -1)
    soft = cv2.GaussianBlur(soft, (0, 0), 6)[..., None]
    dst = arr[282:402, 452:572].astype(np.float32)          # 120 x 120 around (512, 342)
    arr[282:402, 452:572] = (dst * (1 - soft) + src * soft).astype(np.uint8)
    img = Image.fromarray(cv2.cvtColor(arr, cv2.COLOR_BGR2RGB))

    big = img.resize((W * SS, H * SS), Image.LANCZOS).convert("RGBA")
    for _, (cx, cy, r, text, ty) in KNOBS.items():
        caption(big, cx, ty, text, 27 if r > 50 else 24)
    caption(big, 198, 1442, "UP", 29)
    caption(big, 824, 1442, "WAY UP", 29)
    caption(big, 428, 343, "MONO", 20)
    caption(big, 598, 343, "STEREO", 20)

    logo = Image.open(ROOT / "Resources/logo_die_noise.png").convert("RGBA")
    logo = logo.crop(logo.getchannel("A").point(lambda v: 255 if v > 8 else 0).getbbox())
    lw = 396 * SS
    logo = logo.resize((lw, int(logo.height * lw / logo.width)), Image.LANCZOS)
    big.alpha_composite(logo, (511 * SS - lw // 2, 1062 * SS))

    out = big.convert("RGB").resize((W, H), Image.LANCZOS)
    out.save(ROOT / "Resources/skin_source.png")
    out.save(ROOT / "Resources/skin.png")

    def knob(n):
        cx, cy, r, *_ = KNOBS[n]
        return f"inline constexpr Knob {n} {{ {cx:.1f}f, {cy:.1f}f, {r:.1f}f, {r*0.30:.1f}f, {r*0.88:.1f}f, {r*0.13:.1f}f }};"

    lines = [
        "// Generated by tools/make_skin_die_noise.py. Do not edit by hand.",
        "// Positions in artwork pixels (1024 x 1536).",
        "#pragma once", "", "namespace SkinLayout", "{",
        "inline constexpr float width = 1024.0f, height = 1536.0f;", "",
        "// Knob: rotation centre and radius of the top face, pointer from `in` to `out` (radius), width.",
        "struct Knob { float cx, cy, radius, pointerIn, pointerOut, pointerWidth; };",
        *[knob(n) for n in KNOBS], "",
        "struct Circle { float cx, cy, radius; };",
        "inline constexpr Circle prevButton { %.1ff, %.1ff, %.1ff };" % PREV,
        "inline constexpr Circle nextButton { %.1ff, %.1ff, %.1ff };" % NEXT,
        "inline constexpr Circle led { %.1ff, %.1ff, %.1ff };" % LED,
        "// Footswitch: opening around cap and bevel; the whole content slides when pressed.",
        "inline constexpr Circle upSwitch { %.1ff, %.1ff, %.1ff };" % SWITCH["up"],
        "inline constexpr Circle wayUpSwitch { %.1ff, %.1ff, %.1ff };" % SWITCH["wayUp"],
        "inline constexpr float upSwitchAxis = %.1ff, wayUpSwitchAxis = %.1ff;" % (SWITCH["up"][0], SWITCH["wayUp"][0]), "",
        "struct Rect { float x0, y0, x1, y1; };",
        "inline constexpr Rect presetWindow { %.1ff, %.1ff, %.1ff, %.1ff };" % PRESET_WINDOW,
        "inline constexpr bool presetWindowIsDark = true;",
        "inline constexpr Rect toggle { %.1ff, %.1ff, %.1ff, %.1ff };" % TOGGLE,
        "inline constexpr float toggleMirrorX = %.2ff;" % TOGGLE_MIRROR_X, "",
        "// Meter lamps, top to bottom (same rows on both sides), and each column's x span.",
        "inline constexpr int meterLamps = %d;" % len(METER_LAMPS),
        "inline constexpr float meterLampY[meterLamps] { " + ", ".join(f"{y:.1f}f" for y in METER_LAMPS) + " };",
        "inline constexpr Rect meterLeft { %.1ff, %.1ff, %.1ff, %.1ff };" % (METER_LEFT[0], METER_LAMPS[0], METER_LEFT[1], METER_LAMPS[-1]),
        "inline constexpr Rect meterRight { %.1ff, %.1ff, %.1ff, %.1ff };" % (METER_RIGHT[0], METER_LAMPS[0], METER_RIGHT[1], METER_LAMPS[-1]),
        "} // namespace SkinLayout", "",
    ]
    (ROOT / "Source/SkinLayout.h").write_text("\n".join(lines))
    print("wrote Resources/skin.png, Resources/skin_source.png and Source/SkinLayout.h")


if __name__ == "__main__":
    main()
